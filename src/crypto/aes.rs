    fn rejects_partial_blocks() {
        let key = [0u8; 16];
        let iv = [0u8; 16];
        assert!(aes128_cbc_encrypt(&key, &iv, &[0u8; 15]).is_none());
        assert!(aes128_cbc_decrypt(&key, &iv, &[0u8; 17]).is_none());
    }
